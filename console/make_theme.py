#!/usr/bin/env python3
"""Generate console/static/theme.css from design/tokens.json (the JSON stays the source).

Run: python3 console/make_theme.py          writes console/static/theme.css
     python3 console/make_theme.py --check  exits 1 when the committed file is not what the tokens produce

The custom property names are the ones the design's mockups use (--md-sys-color-*, --ext-*, --overlay-*),
so the component layer in static/base.css is the mockups' own. The light theme is the default; the dark
theme applies under ``prefers-color-scheme: dark`` unless the user chose light, and always under
``data-theme="dark"`` (the manual override).
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
TOKENS = HERE.parent / "design" / "tokens.json"
OUT = HERE / "static" / "theme.css"
OVERLAY_VARS = {"scrim": "--overlay-scrim", "hatch": "--overlay-hatch", "shadow_key": "--shadow-key",
                "shadow_ambient": "--shadow-ambient", "live_pulse_low": "--live-pulse-low", "disabled_fg": "--disabled-fg"}


def theme_vars(theme: dict) -> list[tuple[str, str]]:
    out = [(f"--md-sys-color-{k.replace('_', '-')}", v) for k, v in theme["m3"].items()]
    for role in ("live", "ok"):
        out += [(f"--ext-{role}-{k.replace('_', '-')}", v) for k, v in theme["ext"][role].items() if k != "hue"]
    out.append(("--ext-hold-fill", theme["ext"]["hold"]["fill"]))
    return out


def block(selector: str, theme: dict, scheme: str, indent: str = "") -> str:
    lines = [f"{indent}{selector} {{"]
    lines += [f"{indent}  {name}: {value};" for name, value in theme_vars(theme)]
    lines += [f"{indent}  color-scheme: {scheme};", f"{indent}}}"]
    return "\n".join(lines)


def build() -> str:
    tokens = json.loads(TOKENS.read_text())
    overlay = tokens["overlay"]
    parts = ["/* Generated by console/make_theme.py from design/tokens.json. Do not edit. */",
             block(':root, :root[data-theme="light"]', tokens["light"], "light"),
             "@media (prefers-color-scheme: dark) {\n" + block(':root:not([data-theme="light"])', tokens["dark"], "dark", "  ") + "\n}",
             block(':root[data-theme="dark"]', tokens["dark"], "dark"),
             ":root {\n" + "\n".join(f"  {var}: {overlay[key]};" for key, var in OVERLAY_VARS.items()) + "\n}"]
    return "\n".join(parts) + "\n"


def main(argv: list[str]) -> int:
    text = build()
    if "--check" in argv:
        if not OUT.is_file() or OUT.read_text() != text:
            print("console/static/theme.css is not what design/tokens.json produces; run console/make_theme.py")
            return 1
        return 0
    OUT.write_text(text)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
